type Accent = 'acute' | 'grave' | 'circ' | 'diaer' | 'cedil';
const ACCENTED: Record<string, [string, Accent]> = {
  É: ['E', 'acute'], È: ['E', 'grave'], Ê: ['E', 'circ'], Ë: ['E', 'diaer'],
  À: ['A', 'grave'], Â: ['A', 'circ'], Ä: ['A', 'diaer'],
  Î: ['I', 'circ'], Ï: ['I', 'diaer'],
  Ô: ['O', 'circ'], Ö: ['O', 'diaer'],
  Ù: ['U', 'grave'], Û: ['U', 'circ'], Ü: ['U', 'diaer'],
  Ç: ['C', 'cedil'],
};
const ACCENT_PX: Record<Accent, [number, number][]> = {
  acute: [[3, -3], [2, -2]],
  grave: [[1, -3], [2, -2]],
  circ: [[2, -3], [1, -2], [3, -2]],
  diaer: [[1, -2], [3, -2]],
  cedil: [[2, 7], [1, 8]],
};

const parsed = new Map<string, boolean[][]>();
function glyph(ch: string): boolean[][] {
  let g = parsed.get(ch);
  if (!g) {
    const src = G[ch] ?? G['?'];
    g = src.split('|').map((row) => row.split('').map((c) => c === '#'));
    parsed.set(ch, g);
  }
  return g;
}

export const FONT_H = 7;
export const FONT_ADVANCE = 6;

export function textWidth(text: string): number {
  return Math.max(0, text.length * FONT_ADVANCE - 1);
}

export function normalizeSign(text: string): string {
  return (text || '').toLocaleUpperCase('fr-FR').replace(/Œ/g, 'OE').replace(/Æ/g, 'AE');
}

/** Draws pixel text with its top-left at (x, y). Accents use rows -3..-1, cedilla rows 7..8. */
export function drawPixelText(g: Ctx, text: string, x: number, y: number, color: string): void {
  g.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const raw of normalizeSign(text)) {
    const acc = ACCENTED[raw];
    const base = acc ? acc[0] : raw;
    const gl = glyph(G[base] ? base : '?');
    for (let r = 0; r < gl.length; r++) {
      const row = gl[r];
      for (let c = 0; c < row.length; c++) if (row[c]) g.fillRect(cx + c, cy + r, 1, 1);
    }
    if (acc) for (const [ax, ay] of ACCENT_PX[acc[1]]) g.fillRect(cx + ax, cy + ay, 1, 1);
    cx += FONT_ADVANCE;
  }
}
