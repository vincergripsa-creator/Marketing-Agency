/** Tiny pixel-art mascot used by the logo (crisp 8×8 grid). */
export function PixelLogo({ size = 22 }: { size?: number }) {
  const px: [number, number, string][] = [];
  const rows = [
    '..pppp..',
    '.pppppp.',
    'pphpphpp',
    'pppppppp',
    'p.pyyp.p',
    '..pppp..',
    '.cc..cc.',
    '.g....g.',
  ];
  const colors: Record<string, string> = { p: '#f472b6', h: '#0f172a', y: '#fde047', c: '#7dd3fc', g: '#334155' };
  rows.forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== '.') px.push([x, y, colors[ch] ?? '#000']); }));
  return (
    <svg width={size} height={size} viewBox="0 0 8 8" shapeRendering="crispEdges" aria-hidden="true" className="pixel-logo">
      {px.map(([x, y, c]) => <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill={c} />)}
    </svg>
  );
}
